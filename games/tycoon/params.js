// ── 工具 ──
const isLeaf = (o) => o && typeof o === 'object' && 'v' in o && 'src' in o && 'note' in o;

/** 把 { v, src, note } 葉節點攤平成純數值物件，給 sim 用。 */
export function unwrap(node) {
  if (isLeaf(node)) return node.v;
  const out = {};
  for (const k of Object.keys(node)) out[k] = unwrap(node[k]);
  return out;
}

/** 攤平成清單 [{ path, v, src, note }]，給「數字來源」頁用。 */
export function listParams(node = P, path = []) {
  if (isLeaf(node)) return [{ path: path.join('.'), v: node.v, src: node.src, note: node.note }];
  return Object.keys(node).flatMap((k) => listParams(node[k], [...path, k]));
}
